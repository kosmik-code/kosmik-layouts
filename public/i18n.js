const DICTS = { es: ES, en: EN };
const KEY = "kl-lang";
let lang = "en";

/** Stored choice, else the browser's languages (Spanish if any of them is Spanish). */
export function initialLanguage() {
  try {
    const stored = localStorage.getItem(KEY);
    if (DICTS[stored]) return stored;
  } catch {
    // storage blocked: follow the browser
  }
  const wanted = navigator.languages?.length ? navigator.languages : [navigator.language];
  return wanted.some((l) => String(l).toLowerCase().startsWith("es")) ? "es" : "en";
}

export function setLanguage(next, remember = false) {
  lang = DICTS[next] ? next : "en";
  document.documentElement.lang = lang;
  if (remember) {
    try {
      localStorage.setItem(KEY, lang);
    } catch {
      // not remembered
    }
  }
}

export const getLanguage = () => lang;

export function t(key, params = {}) {
  const s = DICTS[lang][key] ?? EN[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
}

/** True when the key exists (used for server reasons that may be new). */
export const has = (key) => key in DICTS[lang] || key in EN;
